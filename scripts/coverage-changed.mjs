#!/usr/bin/env node
// Coverage gate: every changed source file needs ≥ 80 % line coverage (AGENTS.md §9). There is no
// CI (ADR 0004): scripts/check.sh --cov runs it, from the pre-push hook.
// Usage: node scripts/coverage-changed.mjs [--lcov <path>]... [--base <ref>] [--min <pct>]

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const DEFAULT_LCOV = ["coverage/rust.lcov", "coverage/front/lcov.info"];

const GATED = [/^src-tauri\/src\/.+\.rs$/, /^src\/.+\.(ts|svelte)$/];

// Growing this list needs a line in PROGRESS.md.
export const EXCLUDED = [
  /^src-tauri\/src\/macos\//, // thin FFI layer, checked by manual QA (AGENTS.md §9)
  /^src-tauri\/src\/(main|lib)\.rs$/, // Tauri wiring only, run when the app starts: logic goes in tested modules
  /^src\/lib\/bindings\//, // generated by ts-rs
  /\.test\.ts$/,
  /^src\/test\//,
  /^e2e\//,
  /^src-tauri\/tests\//,
  /\.d\.ts$/,
  /^src\/main\.ts$/, // dev harness, covered by e2e/ and left out of the Vitest report
  /^src\/App\.svelte$/,
];

export function normalizePath(path, root) {
  return relative(root, resolve(root, path));
}

// Map of repository-relative path → { found, hit }. Lines are counted from DA records, merged when
// a file appears twice; LF/LH are used when a record has no DA line.
export function parseLcov(text, root) {
  const files = new Map();
  let current = null;
  for (const line of text.split(/\r?\n/)) {
    const [tag, value = ""] = line.split(/:(.*)/s);
    if (tag === "SF") {
      const path = normalizePath(value, root);
      if (!files.has(path)) files.set(path, { lines: new Map(), found: 0, hit: 0 });
      current = files.get(path);
    } else if (!current) {
      continue;
    } else if (tag === "DA") {
      const [number, count] = value.split(",");
      current.lines.set(number, Math.max(current.lines.get(number) ?? 0, Number(count)));
    } else if (tag === "LF") {
      current.found = Number(value);
    } else if (tag === "LH") {
      current.hit = Number(value);
    } else if (line === "end_of_record") {
      current = null;
    }
  }
  return new Map(
    [...files].map(([path, { lines, found, hit }]) =>
      lines.size > 0 ? [path, { found: lines.size, hit: [...lines.values()].filter((count) => count > 0).length }] : [path, { found, hit }],
    ),
  );
}

export function isGated(path) {
  return GATED.some((pattern) => pattern.test(path)) && !EXCLUDED.some((pattern) => pattern.test(path));
}

export function evaluate(changed, coverage, min) {
  const files = changed.filter(isGated).map((path) => {
    const report = coverage.get(path);
    if (!report) return { path, found: 0, hit: 0, pct: 0, ok: false };
    const { found, hit } = report;
    // Integers only: 7 / 10 * 100 is 70.00000000000001.
    return { path, found, hit, pct: found === 0 ? 100 : (hit * 100) / found, ok: hit * 100 >= min * found };
  });
  return { ok: files.every((file) => file.ok), files };
}

function git(cwd, ...args) {
  return execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
}

function changedFiles(root, base) {
  const mergeBase = git(root, "merge-base", "HEAD", base);
  const tracked = git(root, "diff", "--name-only", "--diff-filter=AMR", mergeBase);
  const untracked = git(root, "ls-files", "--others", "--exclude-standard");
  return `${tracked}\n${untracked}`.split("\n").filter(Boolean);
}

function main() {
  const { values } = parseArgs({
    options: {
      lcov: { type: "string", multiple: true },
      base: { type: "string", default: "main" },
      min: { type: "string", default: "80" },
    },
  });
  const min = Number(values.min);
  const root = git(process.cwd(), "rev-parse", "--show-toplevel");
  const coverage = new Map();
  for (const path of values.lcov ?? DEFAULT_LCOV) {
    if (!existsSync(path)) {
      console.error(`⚠ ${path} not found`);
      continue;
    }
    for (const [file, report] of parseLcov(readFileSync(path, "utf8"), root)) coverage.set(file, report);
  }
  const { ok, files } = evaluate(changedFiles(root, values.base), coverage, min);
  if (files.length === 0) {
    console.log("no changed source file");
    return 0;
  }
  for (const file of files) {
    const missing = coverage.has(file.path) ? "" : "  (in no report)";
    console.log(`${file.ok ? "✓" : "✖"} ${file.path}  ${file.hit}/${file.found}  ${(Math.floor(file.pct * 10) / 10).toFixed(1)} %${missing}`);
  }
  if (!ok) console.error(`✖ line coverage below ${min} % on a changed file: add tests (AGENTS.md §9).`);
  return ok ? 0 : 1;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exitCode = main();
  } catch (error) {
    console.error(`✖ ${error.stderr?.toString().trim() || error.message}`);
    process.exitCode = 1;
  }
}
